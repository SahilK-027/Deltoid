import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// RULES § Interface: *a painter never clamps to a bound it computed.*
///
/// `clamp(lower, upper)` throws when `lower > upper`. That is not a rare edge —
/// it is what happens whenever a bound comes from a layout that got small or a
/// list that got long. `WeeklyBars` documented its geometry carefully and still
/// shipped `clamp(1.0, slot)`, which was latent until a range widened enough to
/// reach it and then fatal on every repaint of the volume screen. The comment
/// was correct, load-bearing, and did nothing, which is why the rules that
/// matter in this codebase are mechanical (RULES § 7).
///
/// The mechanical form of this one: **both bounds of a `clamp` must be
/// constants.** A bound built out of arithmetic — `n - 1`, `height / 2`,
/// `size.height * sets / scale` — is one whose ordering nothing checked, and
/// the fix is always the same shape: `max(a, min(b, c))` cannot invert and
/// cannot throw.
///
/// What this deliberately does not do is understand Dart. It is a reader over
/// source text, so it is defeatable by anyone determined to defeat it; it
/// exists to catch the accident, which is the only way this has ever happened.
void main() {
  test('no clamp in lib/ is given a computed bound', () {
    final offenders = <String>[];

    for (final file in Directory('lib')
        .listSync(recursive: true)
        .whereType<File>()
        .where((f) => f.path.endsWith('.dart'))
        // Generated by drift from tables.dart, and not ours to write.
        .where((f) => !f.path.endsWith('.g.dart'))) {
      final source = file.readAsStringSync();
      for (final call in _clampCalls(source)) {
        // `TextScaler.clamp` takes named arguments and is a different method
        // that happens to share the name.
        if (call.args.any((a) => a.contains(':'))) continue;
        if (call.args.length != 2) continue;
        final computed = call.args.where((a) => !_isConstantBound(a)).toList();
        if (computed.isEmpty) continue;
        final line = '\n'.allMatches(source.substring(0, call.offset)).length + 1;
        offenders.add('${file.path}:$line — clamp(${call.args.join(', ')}) '
            '(computed: ${computed.join(', ')})');
      }
    }

    expect(
      offenders,
      isEmpty,
      reason: 'a clamp whose bounds can invert throws where it is drawn. '
          'Write max(a, min(b, c)) instead — RULES § Interface:\n'
          '${offenders.join('\n')}',
    );
  });

  test('the reader can tell a constant bound from a computed one', () {
    // The check above only means something if this does, and every case here
    // is one that appears in lib/.
    expect(_isConstantBound('0'), isTrue);
    expect(_isConstantBound('1.0'), isTrue);
    expect(_isConstantBound('-1'), isTrue);
    expect(_isConstantBound('99'), isTrue);
    expect(_isConstantBound('1 << 30'), isTrue);
    expect(_isConstantBound('_panel'), isTrue);
    expect(_isConstantBound('-_panel'), isTrue);
    expect(_isConstantBound('consistencyWindowDays'), isTrue);
    expect(_isConstantBound('SetRow.doneColumn'), isTrue);

    expect(_isConstantBound('n - 1'), isFalse);
    expect(_isConstantBound('height / 2'), isFalse);
    expect(_isConstantBound('size.height'), isTrue,
        reason: 'a bare property is allowed; the arithmetic is what bites');
    expect(_isConstantBound('weeks.length - 1'), isFalse);
    expect(_isConstantBound('entries.length - 1'), isFalse);
  });

  test('the reader finds the calls it is meant to find', () {
    final found = _clampCalls('''
      final a = x.clamp(0, n - 1);
      final b = (foo(bar, baz)).clamp(1.0, size.height);
      final c = y.clamp(0.0, 1.0);
    ''');
    expect(found.map((c) => c.args).toList(), [
      ['0', 'n - 1'],
      ['1.0', 'size.height'],
      ['0.0', '1.0'],
    ]);
  });
}

/// A bound written as a constant: a number, a shift of two numbers, or a plain
/// identifier or property path with no arithmetic in it.
bool _isConstantBound(String arg) {
  final a = arg.trim();
  if (RegExp(r'^-?\d+(\.\d+)?$').hasMatch(a)) return true;
  if (RegExp(r'^\d+ *<< *\d+$').hasMatch(a)) return true;
  return RegExp(r'^-?[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$')
      .hasMatch(a);
}

typedef _ClampCall = ({int offset, List<String> args});

/// Every `.clamp(…)` in [source], with its arguments split at the commas that
/// are not inside a nested call, list or string.
List<_ClampCall> _clampCalls(String source) {
  final calls = <_ClampCall>[];
  for (final match in RegExp(r'\.clamp\(').allMatches(source)) {
    final open = match.end - 1;
    var depth = 0;
    var start = open + 1;
    final args = <String>[];
    String? quote;
    for (var i = open; i < source.length; i++) {
      final ch = source[i];
      if (quote != null) {
        if (ch == quote) quote = null;
        continue;
      }
      if (ch == "'" || ch == '"') {
        quote = ch;
      } else if (ch == '(' || ch == '[' || ch == '{') {
        depth++;
      } else if (ch == ')' || ch == ']' || ch == '}') {
        depth--;
        if (depth == 0) {
          args.add(source.substring(start, i).trim());
          break;
        }
      } else if (ch == ',' && depth == 1) {
        args.add(source.substring(start, i).trim());
        start = i + 1;
      }
    }
    calls.add((offset: match.start, args: args));
  }
  return calls;
}
